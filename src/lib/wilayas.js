export function getWilaya(code) {
  return WILAYAS.find((w) => w.code === Number(code)) || null;
}

export const FREE_DELIVERY_THRESHOLD = 10000; // دج

export function deliveryFee(wilayaCode, subtotal) {
  if (subtotal >= FREE_DELIVERY_THRESHOLD) return 0;
  const w = getWilaya(wilayaCode);
  return w ? w.fee : 0;
}

